module top ( clk, rstn, in_a, out_y );
  input clk, rstn, in_a;
  output out_y;

  wire n_clk, n_rstn, n_a;
  wire chain [0:119];
  wire q;
  wire res_y;
  wire sram_q;

  // Flat top-level leaf cells (legitimate top-residual).
  INVD1 u_top_inv0 ( .I(clk), .ZN(n_clk) );
  INVD1 u_top_inv1 ( .I(rstn), .ZN(n_rstn) );
  INVD1 u_top_inv2 ( .I(in_a), .ZN(n_a) );

  // A SRAM macro, pre-placed to block a large chunk of the core so the
  // 8x8 region grid has mixed open/blocked regions.
  SP512X40M4 u_sram0 ( .A(n_a), .CLK(n_clk), .CSP(n_rstn), .D(n_a), .WE(n_rstn), .Q(sram_q) );

  // A large hierarchical child holding most std cells in a deep chain.
  big_block core0 ( .clk(n_clk), .a(sram_q), .y(q) );

  DFQD0 u_top_flop ( .CP(n_clk), .D(q), .Q(res_y) );
  assign out_y = res_y;
endmodule

